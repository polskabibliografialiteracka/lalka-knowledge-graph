def find_title_rows(
    df,
    phrase,
):
    """
    Find records whose title contains the given phrase.
    """

    if (
        df is None
        or df.empty
        or "ZA_TYTUL" not in df.columns
    ):
        return (
            df.iloc[0:0]
            if df is not None
            else pd.DataFrame()
        )

    mask = contains_text(
        df["ZA_TYTUL"],
        phrase,
    )

    return df[mask].drop_duplicates()


def print_title_report(
    df,
    phrase,
):
    """
    Print records whose title contains phrase.
    """

    print_subheader(
        f'Title search: "{phrase}"'
    )

    title_df = find_title_rows(
        df,
        phrase,
    )

    if title_df.empty:
        print("  No records found.")
        return

    print(
        f"Records found: "
        f"{len(title_df)}"
    )

    columns = [
        "ZA_ZAPIS_ID",
        "ZAPIS_NADRZEDNY",
        "ZA_TYPE",
        "ZA_RZ_RODZAJ1_ID",
        "RZ_NAZWA",
        "ZA_TYTUL",
        "DZ_DZIAL_ID",
        "DZ_NAZWA",
        "ZR_ZRODLO_ID",
        "ZR_TYTUL",
        "ZA_ZRODLO_ROK",
        "ZA_ROK_WYDANIA",
    ]

    show_dataframe(
        title_df,
        columns=columns,
        max_rows=50,
    )


