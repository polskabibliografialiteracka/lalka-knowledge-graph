def print_author_report(
    authors_df,
    records_df,
    first_name,
    last_name,
):
    """
    Find records associated with an author.
    """

    full_name = (
        f"{first_name} {last_name}"
    )

    print_subheader(
        f"Author: {full_name}"
    )

    if (
        authors_df is None
        or authors_df.empty
    ):
        print("  No author relations available.")
        return

    if (
        "IMIE" not in authors_df.columns
        or "NAZWISKO" not in authors_df.columns
    ):
        print(
            "  Author name columns not available."
        )
        return

    mask = (
        contains_text(
            authors_df["IMIE"],
            first_name,
        )
        &
        contains_text(
            authors_df["NAZWISKO"],
            last_name,
        )
    )

    matches = authors_df[mask].drop_duplicates()

    if matches.empty:
        print("  No records found.")
        return

    print(
        f"Author relations found: "
        f"{len(matches)}"
    )

    show_dataframe(
        matches,
        columns=[
            "ZAPIS_ID",
            "AUTOR_ID",
            "IMIE",
            "NAZWISKO",
        ],
        max_rows=50,
    )

    # -------------------------------------------------------------------------
    # Join with main records
    # -------------------------------------------------------------------------

    if (
        records_df is None
        or records_df.empty
        or "ZA_ZAPIS_ID" not in records_df.columns
        or "ZAPIS_ID" not in matches.columns
    ):
        return

    record_ids = set(
        pd.to_numeric(
            matches["ZAPIS_ID"],
            errors="coerce",
        )
        .dropna()
        .astype(int)
    )

    related_records = records_df[
        pd.to_numeric(
            records_df["ZA_ZAPIS_ID"],
            errors="coerce",
        )
        .isin(record_ids)
    ]

    print()
    print(
        f"Related PBL records: "
        f"{len(related_records)}"
    )

    show_dataframe(
        related_records,
        columns=[
            "ZA_ZAPIS_ID",
            "ZAPIS_NADRZEDNY",
            "ZA_TYPE",
            "RZ_NAZWA",
            "ZA_TYTUL",
            "DZ_NAZWA",
            "ZR_TYTUL",
            "ZA_ZRODLO_ROK",
        ],
        max_rows=50,
    )


