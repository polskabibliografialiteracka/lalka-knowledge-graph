def load_json(path):
    """Load JSON file using UTF-8."""
    with open(path, "r", encoding="utf-8") as file:
        return json.load(file)


def print_separator(char="=", length=80):
    print(char * length)


def print_header(title):
    print()
    print_separator()
    print(title)
    print_separator()


def print_subheader(title):
    print()
    print(f"--- {title} ---")


def safe_str(value):
    """Return a readable string for None / NaN values."""
    if value is None:
        return ""

    if pd.isna(value):
        return ""

    return str(value).strip()


def show_dataframe(df, columns=None, max_rows=20):
    """Print selected dataframe columns."""
    if df.empty:
        print("  No records found.")
        return

    if columns:
        available = [c for c in columns if c in df.columns]
        df = df[available]

    print(df.head(max_rows).to_string(index=False))

    if len(df) > max_rows:
        print(f"\n  ... showing first {max_rows} of {len(df)} records")


def find_person_rows(df, first_name=None, last_name=None):
    """
    Search for a person in both author and creator columns.

    Returns records containing the person as author OR creator.
    """

    conditions = []

    if "AM_IMIE" in df.columns and "AM_NAZWISKO" in df.columns:
        author_condition = pd.Series(True, index=df.index)

        if first_name:
            author_condition &= (
                df["AM_IMIE"]
                .fillna("")
                .astype(str)
                .str.contains(first_name, case=False, na=False)
            )

        if last_name:
            author_condition &= (
                df["AM_NAZWISKO"]
                .fillna("")
                .astype(str)
                .str.contains(last_name, case=False, na=False)
            )

        conditions.append(author_condition)

    if "TW_IMIE" in df.columns and "TW_NAZWISKO" in df.columns:
        creator_condition = pd.Series(True, index=df.index)

        if first_name:
            creator_condition &= (
                df["TW_IMIE"]
                .fillna("")
                .astype(str)
                .str.contains(first_name, case=False, na=False)
            )

        if last_name:
            creator_condition &= (
                df["TW_NAZWISKO"]
                .fillna("")
                .astype(str)
                .str.contains(last_name, case=False, na=False)
            )

        conditions.append(creator_condition)

    if not conditions:
        return df.iloc[0:0]

    combined = conditions[0]

    for condition in conditions[1:]:
        combined |= condition

    return df[combined].drop_duplicates()


def find_title_rows(df, phrase):
    """Find records whose title contains the given phrase."""
    if "ZA_TYTUL" not in df.columns:
        return df.iloc[0:0]

    mask = (
        df["ZA_TYTUL"]
        .fillna("")
        .astype(str)
        .str.contains(phrase, case=False, na=False)
    )

    return df[mask].drop_duplicates()


def print_person_report(df, first_name, last_name):
    """Print all records associated with a person."""
    full_name = f"{first_name} {last_name}"

    print_subheader(full_name)

    person_df = find_person_rows(
        df,
        first_name=first_name,
        last_name=last_name,
    )

    if person_df.empty:
        print("  No records found.")
        return

    print(f"Records found: {len(person_df)}")

    columns = [
        "ZA_ZAPIS_ID",
        "ZAPIS_NADRZEDNY",
        "ZA_TYPE",
        "ZA_TYTUL",
        "DZ_NAZWA",
        "ZR_TYTUL",
        "ZA_ZRODLO_ROK",
        "AM_AUTOR_ID",
        "AM_IMIE",
        "AM_NAZWISKO",
        "TW_TWORCA_ID",
        "TW_IMIE",
        "TW_NAZWISKO",
    ]

    show_dataframe(person_df, columns=columns, max_rows=50)


def print_title_report(df, phrase):
    """Print records whose title contains phrase."""
    print_subheader(f'Title search: "{phrase}"')

    title_df = find_title_rows(df, phrase)

