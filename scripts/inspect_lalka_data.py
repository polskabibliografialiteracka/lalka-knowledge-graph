"""
Lalka Knowledge Graph — data inspection

Inspects JSON files generated by extract_lalka.py.

The script does not modify any data.
It produces a human-readable report in the terminal.

The inspection is designed to work with the exported column names
used by extract_lalka.py, rather than assuming that raw Oracle
column names are present in the JSON files.
"""

from pathlib import Path
