def inspect_records():
    print_header("1. MAIN PBL RECORDS")

    path = FILES["records"]

    print(f"File: {path}")
    print(f"Exists: {path.exists()}")

    if not path.exists():
        print("ERROR: File not found.")
        return None

    records = load_json(path)

    print(f"Type: {type(records).__name__}")
    print(f"Number of objects: {len(records)}")

    if not records:
        print("No records.")
        return None

    df = pd.DataFrame(records)

    print_subheader("Structure")

    print(f"Number of records: {len(df)}")

    print("Columns:")
    for column in df.columns:
        print(f"  - {column}")

    # -------------------------------------------------------------------------
    # Missing values
    # -------------------------------------------------------------------------

    print_subheader("Missing values")

    missing = df.isna().sum()

    missing = missing[missing > 0].sort_values(ascending=False)

    if missing.empty:
        print("  No missing values.")
    else:
        for column, count in missing.items():
            percentage = count / len(df) * 100
            print(f"  - {column}: {count} ({percentage:.1f}%)")

    # -------------------------------------------------------------------------
    # Record types
    # -------------------------------------------------------------------------

    if "ZA_TYPE" in df.columns:
        print_subheader("Record types")

        counts = df["ZA_TYPE"].value_counts(dropna=False)

        for value, count in counts.items():
            print(f"{count:6} | {value}")

    # -------------------------------------------------------------------------
    # PBL sections
    # -------------------------------------------------------------------------

    if "DZ_NAZWA" in df.columns:
        print_subheader("PBL sections")

        counts = df["DZ_NAZWA"].value_counts(dropna=False)

        for value, count in counts.items():
            print(f"{count:6} | {value}")

    # -------------------------------------------------------------------------
    # Sources
    # -------------------------------------------------------------------------

    if "ZR_TYTUL" in df.columns:
        print_subheader("Sources")

        counts = df["ZR_TYTUL"].value_counts(dropna=False).head(30)

        for value, count in counts.items():
            print(f"{count:6} | {value}")

    # -------------------------------------------------------------------------
    # Years
    # -------------------------------------------------------------------------

    print_subheader("Years")

    for column in ["ZA_ZRODLO_ROK", "ZA_ROK_WYDANIA"]:
        if column not in df.columns:
            continue

        numeric = pd.to_numeric(df[column], errors="coerce").dropna()

        if numeric.empty:
            print(f"{column}: no numeric values")
            continue

        print(f"{column}:")
        print(f"  Minimum: {int(numeric.min())}")
        print(f"  Maximum: {int(numeric.max())}")
        print(f"  Unique years: {numeric.nunique()}")

    # -------------------------------------------------------------------------
    # Hierarchy
    # -------------------------------------------------------------------------

    if "ZAPIS_NADRZEDNY" in df.columns:
        print_subheader("Record hierarchy")

        with_parent = df["ZAPIS_NADRZEDNY"].notna().sum()
        without_parent = df["ZAPIS_NADRZEDNY"].isna().sum()

        print(
            f"Records with parent: "
            f"{with_parent} ({with_parent / len(df) * 100:.1f}%)"
        )

        print(
            f"Records without parent: "
            f"{without_parent} ({without_parent / len(df) * 100:.1f}%)"
        )

        parent_counts = (
            df["ZAPIS_NADRZEDNY"]
            .dropna()
            .value_counts()
            .head(20)
        )

        print()
        print("Most frequently referenced parent records:")

        for parent_id, count in parent_counts.items():
            print(f"  {int(parent_id)} -> {count} child records")

    # -------------------------------------------------------------------------
    # Sample
    # -------------------------------------------------------------------------

    print_subheader("Sample records")

    columns = [
        "ZA_ZAPIS_ID",
        "ZAPIS_NADRZEDNY",
        "ZA_TYPE",
        "ZA_TYTUL",
        "DZ_NAZWA",
        "ZR_TYTUL",
        "ZA_ZRODLO_ROK",
        "ZA_ROK_WYDANIA",
    ]

    show_dataframe(df, columns=columns, max_rows=20)

    return df


