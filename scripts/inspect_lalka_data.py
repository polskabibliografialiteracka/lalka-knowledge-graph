# =============================================================================
# HELPERS
# =============================================================================

def load_json(path):
    """Load JSON file using UTF-8."""

    with open(
        path,
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


def print_separator(
    char="=",
    length=80,
):
    print(char * length)


def print_header(title):
    print()
    print_separator()
    print(title)
    print_separator()


def print_subheader(title):
    print()
    print(f"--- {title} ---")


def show_dataframe(
    df,
    columns=None,
    max_rows=20,
):
    """
    Print selected dataframe columns.

    Missing columns are silently ignored.
    This prevents the inspection script from crashing
    when the exported structure changes.
    """

    if df is None or df.empty:
        print("  No records found.")
        return

    if columns:
        available = [
            column
            for column in columns
            if column in df.columns
        ]

        if not available:
            print("  No requested columns available.")
            return

        df = df[available]

    print(
        df.head(max_rows).to_string(
            index=False
        )
    )

    if len(df) > max_rows:
        print(
            f"\n  ... showing first "
            f"{max_rows} of {len(df)} records"
        )


def contains_text(
    series,
    phrase,
):
    """
    Case-insensitive text search.
    """

    return (
        series
        .fillna("")
        .astype(str)
        .str.contains(
            phrase,
            case=False,
            na=False,
            regex=False,
        )
    )


