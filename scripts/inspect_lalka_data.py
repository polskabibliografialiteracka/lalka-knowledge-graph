def find_person_rows(
    df,
    first_name=None,
    last_name=None,
):
    """
    Search for a person in author and creator relations.

    This function is kept for compatibility with older exports.
    The current records JSON does not contain author / creator
    names directly, so person reports are performed separately
    using authors_df and creators_df.
    """

    if df is None or df.empty:
        return df.iloc[0:0] if df is not None else pd.DataFrame()

    conditions = []

    # -------------------------------------------------------------------------
    # Authors
    # -------------------------------------------------------------------------

    if (
        "IMIE" in df.columns
        and "NAZWISKO" in df.columns
    ):

        condition = pd.Series(
            True,
            index=df.index,
        )

        if first_name:
            condition &= contains_text(
                df["IMIE"],
                first_name,
            )

        if last_name:
            condition &= contains_text(
                df["NAZWISKO"],
                last_name,
            )

        conditions.append(condition)

    # -------------------------------------------------------------------------
    # Creators
    # -------------------------------------------------------------------------

    if (
        "TW_IMIE" in df.columns
        and "TW_NAZWISKO" in df.columns
    ):

        condition = pd.Series(
            True,
            index=df.index,
        )

        if first_name:
            condition &= contains_text(
                df["TW_IMIE"],
                first_name,
            )

        if last_name:
            condition &= contains_text(
                df["TW_NAZWISKO"],
                last_name,
            )

        conditions.append(condition)

    if not conditions:
        return df.iloc[0:0]

    combined = conditions[0]

    for condition in conditions[1:]:
        combined |= condition

    return df[combined].drop_duplicates()


