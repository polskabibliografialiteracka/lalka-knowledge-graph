    id_column = "AUTOR_ID"

    if id_column in df.columns:
        print_subheader("Unique authors")

        print(
            f"Unique author IDs: "
            f"{df[id_column].dropna().nunique()}"
        )

    # -------------------------------------------------------------------------
    # Most frequent authors
    # -------------------------------------------------------------------------

    if "IMIE" in df.columns and "NAZWISKO" in df.columns:

        print_subheader("Most frequent authors")

        temp = df.copy()

        temp["PERSON"] = (
            temp["IMIE"].fillna("").astype(str).str.strip()
            + " "
            + temp["NAZWISKO"].fillna("").astype(str).str.strip()
        ).str.strip()

        counts = temp["PERSON"].value_counts().head(30)

        for person, count in counts.items():
            print(f"{count:4} | {person}")

    return df


